// Package causalgo provides algorithms for causal analysis and discovery.
//
// CausalGo implements three complementary approaches:
//
//   - [github.com/causalgo/causalgo/surd] — information-theoretic SURD decomposition
//     (Synergistic-Unique-Redundant) from Nature Communications 2024
//   - [github.com/causalgo/causalgo/scic] — SCIC (Signed Causal Information Components),
//     an original method for directional causality with conflict detection
//   - [github.com/causalgo/causalgo/varselect] — LASSO-based recursive variable selection
//
// See individual package documentation for usage examples.
package causalgo
